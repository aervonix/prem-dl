// Command buildsecret writes the build secret into a release build, and takes it out again.
//
//	... | go run ./cmd/buildsecret          # the secret on stdin (project.py secret-file --format raw --out -)
//	go run ./cmd/buildsecret -target linux-x64-deb   # the update target of the next build
//	go run ./cmd/buildsecret -remove        # after the build (both files)
//
// The secret goes into internal/selfupdate/secret_release.go, XORed with a random key so a
// strings search of the binary doesn't find it (it is obfuscated, not hidden: anyone with the
// release binary can get it out, which the server is built for). The file is gitignored;
// this refuses to write it otherwise, and never prints the secret.
package main

import (
	"bufio"
	"crypto/rand"
	"flag"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"strings"

	"yt-dlp-gui/internal/selfupdate"
)

const (
	target     = "internal/selfupdate/secret_release.go"
	targetFile = "internal/selfupdate/target_release.go"
)

func main() {
	remove := flag.Bool("remove", false, "delete the files again")
	buildTarget := flag.String("target", "", "write the update target of the next build (windows-x64, linux-x64-appimage, linux-x64-deb) instead")
	flag.Parse()
	if *remove {
		for _, f := range []string{target, targetFile} {
			if err := os.Remove(filepath.FromSlash(f)); err != nil && !os.IsNotExist(err) {
				fail(err.Error())
			}
		}
		return
	}
	if *buildTarget != "" {
		writeTarget(*buildTarget)
		return
	}
	if err := exec.Command("git", "check-ignore", "-q", target).Run(); err != nil {
		fail(target + " isn't gitignored; refusing to write a secret into it")
	}
	line, _ := bufio.NewReader(os.Stdin).ReadString('\n')
	secret := strings.TrimSpace(line)
	if !selfupdate.ValidSecret(secret) {
		fail("stdin didn't hold a build secret (trb_...)")
	}
	key := make([]byte, len(secret))
	if _, err := rand.Read(key); err != nil {
		fail(err.Error())
	}
	data := make([]byte, len(secret))
	for i := range data {
		data[i] = secret[i] ^ key[i]
	}
	src := fmt.Sprintf(`// Code generated by cmd/buildsecret for a release build. DO NOT COMMIT (it is gitignored).

package selfupdate

func init() {
	buildSecret = func() string {
		k := []byte{%s}
		d := []byte{%s}
		for i := range d {
			d[i] ^= k[i]
		}
		return string(d)
	}
}
`, byteList(key), byteList(data))
	if err := os.WriteFile(filepath.FromSlash(target), []byte(src), 0o600); err != nil {
		fail(err.Error())
	}
	id := strings.SplitN(secret, "_", 3)[1]
	fmt.Printf("wrote %s (build secret %s)\n", target, id)
}

// writeTarget writes the build's update target (selfupdate.BuildTarget) into a gitignored file.
func writeTarget(t string) {
	switch t {
	case selfupdate.TargetWindows, selfupdate.TargetAppImage, selfupdate.TargetDeb:
	default:
		fail("unknown target " + t)
	}
	if err := exec.Command("git", "check-ignore", "-q", targetFile).Run(); err != nil {
		fail(targetFile + " isn't gitignored; refusing to write it")
	}
	src := fmt.Sprintf(`// Code generated by cmd/buildsecret for a release build. DO NOT COMMIT (it is gitignored).

package selfupdate

func init() { buildTarget = %q }
`, t)
	if err := os.WriteFile(filepath.FromSlash(targetFile), []byte(src), 0o644); err != nil {
		fail(err.Error())
	}
	fmt.Printf("wrote %s (%s)\n", targetFile, t)
}

func byteList(b []byte) string {
	parts := make([]string, len(b))
	for i, x := range b {
		parts[i] = fmt.Sprintf("0x%02x", x)
	}
	return strings.Join(parts, ", ")
}

func fail(msg string) {
	fmt.Fprintln(os.Stderr, "buildsecret: "+msg)
	os.Exit(1)
}
